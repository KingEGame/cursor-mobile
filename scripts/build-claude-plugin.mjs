#!/usr/bin/env node
/**
 * Bundle the cursor-mobile MCP server into the Claude Code plugin as one self-contained
 * file (claude-plugin/cursor-hub/server/cursor-mcp.mjs), so the plugin works after Claude
 * copies it into its plugin cache.
 */
import { build } from "esbuild";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
await build({
  entryPoints: [join(root, "packages/mcp/src/index.ts")],
  outfile: join(root, "claude-plugin/cursor-hub/server/cursor-mcp.mjs"),
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node20",
  minify: true,
  legalComments: "none",
  banner: { js: "// Generated by scripts/build-claude-plugin.mjs from packages/mcp — do not edit.\nimport { createRequire as __cr } from 'node:module'; const require = __cr(import.meta.url);" },
  logLevel: "warning",
});
console.log("built claude-plugin/cursor-hub/server/cursor-mcp.mjs");
